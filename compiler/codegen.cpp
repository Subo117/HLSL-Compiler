// =======================================================================
// File: compiler/codegen.cpp
// Description: Phase 4 - Code Generation (HLSL Generator)
// Generates valid, error-free HLSL shader code from ValidatedShaderData.
// No user-defined header files are used.
// =======================================================================

#ifndef CODEGEN_CPP
#define CODEGEN_CPP

#include <iostream>
#include <string>
#include <sstream>
#include <iomanip>

using namespace std;

// ---------------------------------------------------------
// Code Generator Class
// ---------------------------------------------------------
class CodeGenerator {
public:
    static string generateHLSL(const ValidatedShaderData& data) {
        stringstream hlsl;

        hlsl << "// ==================================================================\n";
        hlsl << "// HLSL Shader: " << data.shaderName << "\n";
        hlsl << "// Generated by mysh Compiler (Domain Specific Shader Language)\n";
        hlsl << "// Phases executed: Lexer -> Parser -> Semantic -> Codegen\n";
        hlsl << "// ==================================================================\n\n";

        // Constant Buffer
        hlsl << "cbuffer ShaderProperties : register(b0)\n";
        hlsl << "{\n";
        hlsl << "    // Base color: " << data.colorName << "\n";
        hlsl << "    float4 _BaseColor = float4(" 
             << fixed << setprecision(3)
             << data.colorR << "f, " 
             << data.colorG << "f, " 
             << data.colorB << "f, " 
             << data.colorA << "f);\n\n";

        hlsl << "    // Procedural noise parameters\n";
        hlsl << "    float  _NoiseScale = " << data.noiseScale << "f;\n";
        hlsl << "    float  _NoiseSpeed = " << data.noiseSpeed << "f;\n\n";

        hlsl << "    // Visual effect parameters\n";
        hlsl << "    float  _Distortion = " << data.distortion << "f;\n";
        hlsl << "    float  _Emission   = " << data.emission << "f;\n";
        hlsl << "    float  _Time       = 0.0f;\n";
        hlsl << "};\n\n";

        // Vertex & Pixel Shader Inputs/Outputs
        hlsl << "// Vertex Input Structure\n";
        hlsl << "struct VS_INPUT\n";
        hlsl << "{\n";
        hlsl << "    float3 position : POSITION;\n";
        hlsl << "    float2 uv       : TEXCOORD0;\n";
        hlsl << "};\n\n";

        hlsl << "// Pixel Shader Input Structure\n";
        hlsl << "struct PS_INPUT\n";
        hlsl << "{\n";
        hlsl << "    float4 position : SV_POSITION;\n";
        hlsl << "    float2 uv       : TEXCOORD0;\n";
        hlsl << "};\n\n";

        // Procedural 2D Noise Helper Functions
        hlsl << "// ------------------------------------------------------------------\n";
        hlsl << "// Helper Functions: Procedural Value Noise\n";
        hlsl << "// ------------------------------------------------------------------\n";
        hlsl << "float hash21(float2 p)\n";
        hlsl << "{\n";
        hlsl << "    p = frac(p * float2(123.34, 456.21));\n";
        hlsl << "    p += dot(p, p + 45.32);\n";
        hlsl << "    return frac(p.x * p.y);\n";
        hlsl << "}\n\n";

        hlsl << "float simpleNoise(float2 uv)\n";
        hlsl << "{\n";
        hlsl << "    float2 id = floor(uv);\n";
        hlsl << "    float2 f = frac(uv);\n";
        hlsl << "    f = f * f * (3.0 - 2.0 * f); // Hermite smooth interpolation\n\n";
        hlsl << "    float bl = hash21(id);\n";
        hlsl << "    float br = hash21(id + float2(1.0, 0.0));\n";
        hlsl << "    float tl = hash21(id + float2(0.0, 1.0));\n";
        hlsl << "    float tr = hash21(id + float2(1.0, 1.0));\n\n";
        hlsl << "    return lerp(lerp(bl, br, f.x), lerp(tl, tr, f.x), f.y);\n";
        hlsl << "}\n\n";

        // Vertex Shader
        hlsl << "// ------------------------------------------------------------------\n";
        hlsl << "// Vertex Shader: VSMain\n";
        hlsl << "// ------------------------------------------------------------------\n";
        hlsl << "PS_INPUT VSMain(VS_INPUT input)\n";
        hlsl << "{\n";
        hlsl << "    PS_INPUT output;\n";
        hlsl << "    output.position = float4(input.position, 1.0f);\n";
        hlsl << "    output.uv = input.uv;\n";
        hlsl << "    return output;\n";
        hlsl << "}\n\n";

        // Pixel Shader
        hlsl << "// ------------------------------------------------------------------\n";
        hlsl << "// Pixel Shader: PSMain\n";
        hlsl << "// ------------------------------------------------------------------\n";
        hlsl << "float4 PSMain(PS_INPUT input) : SV_TARGET\n";
        hlsl << "{\n";
        hlsl << "    float2 uv = input.uv;\n\n";

        if (data.hasNoise) {
            hlsl << "    // Calculate procedural noise pattern with scale and animated speed\n";
            hlsl << "    float noiseSample = simpleNoise(uv * _NoiseScale + float2(0.0, _Time * _NoiseSpeed));\n\n";
            hlsl << "    // Apply distortion based on noise value\n";
            hlsl << "    float2 distortedUV = uv + (noiseSample - 0.5f) * _Distortion;\n";
            hlsl << "    float distortedNoise = simpleNoise(distortedUV * _NoiseScale);\n\n";
            hlsl << "    // Base color modulated by noise\n";
            hlsl << "    float4 finalColor = _BaseColor * (0.4f + 0.6f * distortedNoise);\n";
        } else {
            hlsl << "    // Simple base color without procedural noise\n";
            hlsl << "    float4 finalColor = _BaseColor;\n";
        }

        hlsl << "\n    // Apply emission intensity boost\n";
        hlsl << "    finalColor.rgb += _BaseColor.rgb * _Emission;\n\n";
        hlsl << "    return saturate(finalColor);\n";
        hlsl << "}\n";

        return hlsl.str();
    }
};

#endif // CODEGEN_CPP
